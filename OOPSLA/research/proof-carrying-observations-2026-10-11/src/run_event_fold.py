"""Run event-fold certificates on QUITS DEMs and qecc native circuits."""
import hashlib
import json
from pathlib import Path
import stim
import time
import numpy as np
from quits.decoder.base import detector_error_model_to_matrix

from kernel.event_fold import Event, check_probability_only, events_from_dem


ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT.parent / "substitution-validation-2026-10-10"


def circuit_events(circuit):
    events = []
    for inst in circuit.flattened():
        # Native qecc Simulation events: operation name and ordered targets are
        # structural; numerical args are probability/noise payload.
        targets = tuple(str(t) for t in inst.targets_copy())
        args = tuple(float(x) for x in inst.gate_args_copy())
        events.append(Event(inst.name, targets, (), args[0] if args else 0.0))
    return tuple(events)


def main():
    results = {}
    qpaths = [OLD / "results" / "quits" / "normal.dem", OLD / "results" / "quits" / "lower.dem"]
    qold = stim.DetectorErrorModel(qpaths[0].read_text(encoding="utf-8"))
    qnew = stim.DetectorErrorModel(qpaths[1].read_text(encoding="utf-8"))
    q = check_probability_only(events_from_dem(qold), events_from_dem(qnew))
    matrices_old = detector_error_model_to_matrix(qold)
    matrices_new = detector_error_model_to_matrix(qnew)
    def fold_matches_native(result, matrices):
        h = np.zeros(matrices[0].shape, dtype=np.uint8)
        logical = np.zeros(matrices[1].shape, dtype=np.uint8)
        for col, (targets, obs) in enumerate(result.columns):
            h[list(targets), col] = 1
            logical[list(obs), col] = 1
        return (np.array_equal(h, matrices[0].toarray()) and
                np.array_equal(logical, matrices[1].toarray()) and
                np.array_equal(np.array(result.priors), matrices[2]))
    q["fold_exactly_matches_native_old"] = fold_matches_native(q["old"], matrices_old)
    q["fold_exactly_matches_native_new"] = fold_matches_native(q["new"], matrices_new)
    assert q["fold_exactly_matches_native_old"] and q["fold_exactly_matches_native_new"]
    q["source_sha256"] = [hashlib.sha256(p.read_bytes()).hexdigest() for p in qpaths]
    q["consumer_relation"] = "detector/observable matrices equal after fold; priors may differ"
    # Producer-side constructive stream: probabilities are changed while the
    # original ordered event labels remain immutable. No second DEM is parsed.
    source_events = events_from_dem(qold)
    generated = tuple(Event(e.kind, e.targets, e.observables,
                            e.probability * 0.2 if e.kind == "error" else e.probability)
                      for e in source_events)
    t0 = time.perf_counter_ns(); constructive = check_probability_only(source_events, generated); constructive_ns = time.perf_counter_ns() - t0
    q["constructive_stream"] = {"accepted": constructive["accepted"],
                                 "new_dem_parse_count": 0,
                                 "generated_event_fold_visits": len(generated),
                                 "old_event_count": len(source_events),
                                 "proof_check_ns": constructive_ns,
                                 "probabilities_changed": any(a.probability != b.probability for a,b in zip(source_events, generated))}
    bad_target = list(generated); i = next(i for i,e in enumerate(bad_target) if e.kind == "error")
    bad_target[i] = Event("error", bad_target[i].targets + (999999,), bad_target[i].observables, bad_target[i].probability)
    bad_range = list(generated); j = next(i for i,e in enumerate(bad_range) if e.kind == "error")
    bad_range[j] = Event("error", bad_range[j].targets, bad_range[j].observables, 0.7)
    q["failure_witnesses"] = {"target_change_rejected": not check_probability_only(source_events, tuple(bad_target))["accepted"],
                               "range_change_rejected": not check_probability_only(source_events, tuple(bad_range))["accepted"]}
    # First observable is semantic: swapping otherwise identical detector
    # events with different observable labels changes the native L column.
    first = stim.DetectorErrorModel("error(0.1) D0 L0\nerror(0.2) D0 L1")
    swapped = stim.DetectorErrorModel("error(0.2) D0 L1\nerror(0.1) D0 L0")
    q["failure_witnesses"]["first_label_reordering_rejected"] = not check_probability_only(events_from_dem(first), events_from_dem(swapped))["accepted"]
    q["failure_witnesses"]["native_first_label_reordering_changes_L"] = not np.array_equal(detector_error_model_to_matrix(first)[1].toarray(), detector_error_model_to_matrix(swapped)[1].toarray())
    results["quits_detector_error_model_to_matrix"] = q
    # Native second-system Simulation outputs were generated by run_qecc.py;
    # parse its actual saved circuits, without using a study adapter output.
    ep = OLD / "results" / "qecc"
    eold = stim.Circuit((ep / "baseline.stim").read_text(encoding="utf-8"))
    enew = stim.Circuit((ep / "idle-change.stim").read_text(encoding="utf-8"))
    oe, ne = circuit_events(eold), circuit_events(enew)
    # Circuit event relation is structural operation/target equality, including
    # detector/observable instructions; noise argument may differ.
    old_struct = tuple((e.kind, e.targets, e.observables) for e in oe)
    new_struct = tuple((e.kind, e.targets, e.observables) for e in ne)
    results["qecc_native_Simulation"] = {
        "accepted": old_struct == new_struct,
        "structural_events_equal": old_struct == new_struct,
        "old_events": len(oe), "new_events": len(ne),
        "producer": "third_party/qecc_routing Simulation",
        "consumer": "circuit schema/noise_free/observable structure",
        "source_sha256": hashlib.sha256((OLD / "results" / "qecc" / "baseline.stim").read_bytes()).hexdigest(),
        "range_checked": all((not e.probability or 0 < e.probability < 0.5) for e in oe + ne),
    }
    assert q["accepted"]
    assert q["constructive_stream"]["accepted"] and q["constructive_stream"]["probabilities_changed"]
    assert all(q["failure_witnesses"].values())
    assert results["qecc_native_Simulation"]["accepted"]
    out = ROOT / "results" / "event-fold.json"
    out.write_text(json.dumps(results, indent=2, default=lambda x: x.__dict__), encoding="utf-8")
    print({k: {a: v for a, v in row.items() if a in {"accepted", "columns_equal", "structural_events_equal", "events_compared", "old_events", "new_events"}} for k, row in results.items()})


if __name__ == "__main__":
    main()
